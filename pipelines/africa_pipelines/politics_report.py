"""data/politics_review_report.md: leaders and elections for review before approval."""

from __future__ import annotations

from typing import TYPE_CHECKING

from .gold_common import countries

if TYPE_CHECKING:
    from .politics import Result

STATUS_LABELS = {
    "within_12_months": "Election within 12 months",
    "beyond_12_months": "No election within 12 months",
    "no_date_set": "No date set",
}
PRECISION_NOTE = {
    "day": "",
    "month": " (by the end of the month)",
    "year": " (by the end of the year)",
}


def render(result: Result) -> str:
    from .politics import election_status

    names = {c.iso3: c.name for c in countries()}
    out: list[str] = []
    w = out.append
    w("# Leaders and elections review report")
    w("")
    w(
        "Generated by `python -m pipelines politics`; overwritten each run. Sources: Wikipedia's "
        "*List of current heads of state and government* (revision "
        f"{result.revisions.get('wikipedia-current-leaders')}) and *List of next general "
        f"elections* (revision {result.revisions.get('wikipedia-next-elections')}), with Wikidata "
        "as a cross-check. Rules: `docs/vinara-method.md` (Leaders and elections)."
    )
    w("")
    w("## Approval")
    w("")
    if result.approved is None:
        w(
            "**Awaiting approval.** `load` skips leaders and elections until the records below "
            "are approved (`python -m pipelines politics --approve`)."
        )
    elif result.changes:
        w(
            f"**{len(result.changes)} change(s) since the snapshot approved on "
            f"{result.approved['approved_on']}.** The site keeps the approved records until the "
            "changes are approved."
        )
    else:
        w(f"Approved on {result.approved['approved_on']}; the lists have not changed since.")
    w("")
    if result.changes and result.approved is not None:
        for change in result.changes:
            w(f"- {change}")
        w("")

    w(f"## Leaders and next elections ({result.today:%d %B %Y})")
    w("")
    w(
        "The executive first (the office the list marks as holding executive power), then the "
        "other of head of state and head of government where it is a different person. Status "
        "counts 12 months from the report's date; a month or year alone is the latest possible "
        "date, by the list's convention."
    )
    w("")
    w("| Country | Executive | Other | Election deciding the executive | Status |")
    w("|---|---|---|---|---|")
    elections = {e.iso3: e for e in result.elections}
    for country in sorted(countries(), key=lambda c: c.name):
        held = [x for x in result.leaders if x.iso3 == country.iso3]
        executive = next(x for x in held if x.executive)
        other = next((x for x in held if not x.executive), None)

        def describe(leader: object) -> str:
            from .politics import Leader

            assert isinstance(leader, Leader)
            tags = [
                t
                for t, on in (("transitional", leader.transitional), ("de facto", leader.de_facto))
                if on
            ]
            qid = f" `{leader.wikidata_qid}`" if leader.wikidata_qid else " (no Wikidata item)"
            return f"{leader.title} – {leader.person}{qid}" + (
                f" *({', '.join(tags)})*" if tags else ""
            )

        election = elections[country.iso3]
        if election.decides == "none":
            when = "No national elections"
        elif election.next_date is None:
            when = f"{election.kind}: no date set"
        else:
            precision = PRECISION_NOTE[election.next_precision or "day"]
            when = f"{election.kind}: {election.next_date}{precision}"
        status = STATUS_LABELS[election_status(election, result.today)]
        w(
            f"| {country.name} | {describe(executive)} | {describe(other) if other else '—'} | "
            f"{when} | {status} |"
        )
    w("")

    w("## Notes shown with a country")
    w("")
    for iso3, text in sorted(result.notes.items(), key=lambda kv: names[kv[0]]):
        w(f"- **{names[iso3]}:** {text}")
    w("")

    w("## Wikidata cross-check")
    w("")
    if result.wikidata_differences:
        w(
            "Wikidata often keeps former office holders without an end date, so differences are "
            "common and are not changes on their own; each is worth a look."
        )
        w("")
        for difference in result.wikidata_differences:
            w(f"- {difference}")
    else:
        w("Wikidata agrees on every office holder.")
    w("")
    if result.warnings:
        w("## Warnings")
        w("")
        for warning in result.warnings:
            w(f"- {warning}")
        w("")
    return "\n".join(out)
