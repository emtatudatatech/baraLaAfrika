"""data/fx_review_report.md: the exchange rates, for review before they are loaded."""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

from .gold_common import countries

if TYPE_CHECKING:
    from .fx import Result

OUTCOMES = {
    "converted": "the IMF gives earlier months in the old unit; converted to the new",
    "already_on_new_unit": "the IMF already gives earlier months in the new unit",
    "outside_series": "outside the months the series covers",
}
CENTRAL_BANKS = (
    "Searched on 22 October 2026 for official central-bank series to replace stale IMF data. "
    "None offers a downloadable series with stated terms of reuse: the Bank of Sierra Leone "
    "publishes daily reference-rate PDFs (no reuse terms found); the Banque Centrale de Mauritanie "
    "publishes a reference rate (no download found); no current official series was found for "
    "Sudan, Guinea or Somalia. As decided, these series are shown to their last month, marked "
    "stale, and left out of currency rankings for windows they do not cover."
)


def _source_label(source_key: str | None) -> str:
    from .fx import reference

    if source_key is None:
        return "—"
    if source_key == "ecb-exr":
        return "ECB"
    if source_key == "bis-xru":
        return "BIS"
    banks = reference()["daily"]["central_banks"]
    return next(
        (b["name"] for b in banks.values() if f"cb-{b['provider'].lower()}" == source_key),
        source_key,
    )


def _monthly_reason(code: str) -> str:
    from .fx import reference

    daily = reference()["daily"]
    bank = daily["central_banks"].get(code)
    if bank is not None and bank["terms"] in daily["usable_terms"]:
        return (
            f"the {bank['name']}'s rates could not be downloaded in this run (the source did not "
            "answer); every refresh tries again"
        )
    if bank is not None and bank["terms"] == "unconfirmed":
        return (
            f"the {bank['name']} publishes daily rates, but its terms could not be read; added "
            "once they are confirmed"
        )
    if bank is not None and bank["terms"] == "permission_required":
        return f"the {bank['name']}'s terms require permission to reuse its rates"
    if code in daily.get("no_rate_since_floor", {}):
        return str(daily["no_rate_since_floor"][code])
    if code in daily["starts_after_floor"]:
        return str(daily["starts_after_floor"][code])
    return "no official daily source usable without permission"


def _rate(value: float) -> str:
    return f"{value:,.0f}" if value >= 1000 else f"{value:,.4g}"


def render(result: Result) -> str:
    from .fx import reference

    names = {c.iso3: c.name for c in countries()}
    ref = reference()
    out: list[str] = []
    w = out.append
    w("# Exchange rates review report")
    w("")
    w(
        "Generated by `python -m pipelines fx`; overwritten each run. Sources and rules: "
        "`docs/vinara-sources.md` (§4–5) and `docs/vinara-method.md` (Exchange rates). Rates are "
        "local currency per US dollar."
    )
    w("")
    w("## Summary")
    w("")
    counts: dict[str, int] = {}
    for s in result.statuses:
        counts[s.status] = counts.get(s.status, 0) + 1
    w(
        f"- **Monthly (IMF):** {len(result.monthly):,} country-months, "
        f"newest {result.newest:%B %Y}; "
        + ", ".join(f"{n} {k}" for k, n in sorted(counts.items()))
        + f" (current: at most {ref['current_within_months']} months behind the newest; "
        f"stale: more than {ref['stale_after_months']})."
    )
    last_year = result.today.year - 1
    december = result.today.replace(year=last_year, month=12, day=1)
    daily_last: dict[str, Any] = {}
    for d in result.daily:
        daily_last[d.currency] = max(daily_last.get(d.currency, d.date), d.date)

    def reaches_december(status: Any) -> bool:
        """Monthly to December, or daily into its last days."""
        daily_end = daily_last.get(ref["currencies"][status.iso3])
        monthly = status.last is not None and status.last >= december
        daily = daily_end is not None and daily_end >= december.replace(day=24)
        return monthly or daily

    short = [names[s.iso3] for s in result.statuses if not reaches_december(s)]
    w(
        f"- **Through {last_year}:** {54 - len(short)} of 54 states have rates (daily or "
        f"monthly) to December {last_year}, the end of the default window; "
        + (", ".join(sorted(short)) if short else "none")
        + " stop earlier, so their currency performance over that window cannot be measured "
        "(they take no part in that ranking, and the site says so)."
    )
    daily_states = [
        iso3 for iso3, code in ref["currencies"].items() if code in result.daily_sources
    ]
    w(
        f"- **Daily (official):** {len(daily_states)} of 54 states, {ref['daily']['start']} to "
        f"{result.daily_last}, {len(result.daily):,} rates for {len(result.daily_sources)} "
        "currencies (states sharing a currency share its rates). The other "
        f"{54 - len(daily_states)} keep the IMF's monthly rates; the reasons are below."
    )
    w(f"- **ISO 4217:** every currency checked against the list published {result.iso_published}.")
    w("")

    w("## Coverage")
    w("")
    w(
        "| Country | Currency | Daily source | Daily from–to | IMF monthly from–to "
        "| Monthly status |"
    )
    w("|---|---|---|---|---|---|")
    days_by_currency: dict[str, list[Any]] = {}
    for d in result.daily:
        days_by_currency.setdefault(d.currency, []).append(d.date)
    for s in sorted(result.statuses, key=lambda s: names[s.iso3]):
        code = ref["currencies"][s.iso3]
        days = days_by_currency.get(code)
        source = _source_label(result.daily_sources.get(code)) if days else "— (monthly only)"
        daily_span = f"{min(days)} – {max(days)}" if days else "—"
        monthly = f"{s.first:%Y-%m} – {s.last:%Y-%m}" if s.first and s.last else "—"
        behind = f" ({s.months_behind} months behind)" if s.months_behind else ""
        w(
            f"| {names[s.iso3]} | {code} | {source} | {daily_span} | {monthly} "
            f"| {s.status}{behind} |"
        )
    w("")
    w("### Monthly only, and why")
    w("")
    for iso3, code in sorted(ref["currencies"].items(), key=lambda kv: names[kv[0]]):
        if code in result.daily_sources:
            continue
        w(f"- **{names[iso3]}** ({code}): {_monthly_reason(code)}.")
    w("")
    stale = [s for s in result.statuses if s.status == "stale"]
    replaced = [s for s in stale if ref["currencies"][s.iso3] in result.daily_sources]
    stale = [s for s in stale if s not in replaced]
    if stale:
        w(
            "**Stale:** "
            + ", ".join(f"{names[s.iso3]} (to {s.last:%b %Y})" for s in stale if s.last)
            + ". "
            + CENTRAL_BANKS
        )
        w("")
    if replaced:
        w(
            "**Stale IMF series, current daily rates:** "
            + ", ".join(f"{names[s.iso3]} (IMF to {s.last:%b %Y})" for s in replaced if s.last)
            + ". Their own central banks' daily rates are current, so they are shown and ranked "
            "from those."
        )
        w("")
    for iso3, start in ref.get("series_start", {}).items():
        w(f"**{names[iso3]} starts {start['month']}:** {start['reason']}")
        w("")

    w("## Currency changes")
    w("")
    w("| Country | Date | Change | Old per new | Handling | Last old-unit month → first new |")
    w("|---|---|---|---|---|---|")
    for c in sorted(result.changes, key=lambda c: c.date):
        step = f"{_rate(c.before)} → {_rate(c.after)}" if c.before and c.after else "—"
        w(
            f"| {names[c.iso3]} | {c.date} | {c.old} → {c.new} | {c.old_per_new:,g} | "
            f"{OUTCOMES[c.outcome]} | {step} |"
        )
    w("")

    w("## Pegs checked against the IMF")
    w("")
    w(
        f"Months within {ref['peg_tolerance']:.0%} of the official parity (euro pegs on the IMF's "
        "euro rate, dollar pegs on its dollar rate, rand-linked currencies on South Africa's). "
        f"The run requires 95% over the last {ref['peg_check_months']} months; older deviations "
        "are the IMF series' own (cross rates and timing), listed for the record."
    )
    w("")
    w("| Country | Currency | Peg | Last ten years | Largest | Whole series | Largest |")
    w("|---|---|---|---|---|---|---|")
    for iso3, (ok, total, worst) in sorted(result.peg_checks.items(), key=lambda kv: names[kv[0]]):
        code = ref["currencies"][iso3]
        peg = ref["pegs"][code]
        all_ok, all_total, all_worst = result.peg_history.get(iso3, (ok, total, worst))
        w(
            f"| {names[iso3]} | {code} | {peg['parity']:g} per {peg['anchor']} | {ok} of {total} | "
            f"{worst:.2%} | {all_ok} of {all_total} | {all_worst:.2%} |"
        )
    w("")
    w(
        "Eritrea's nakfa is fixed by the Bank of Eritrea; the IMF series shows 15.075 and 15.375 "
        "per dollar in different periods, so no single parity is recorded and the IMF series is "
        "used as published."
    )
    w("")

    w("## Daily rates checked against the IMF")
    w("")
    w("Monthly means of the daily rates against the IMF's monthly average.")
    w("")
    w("| Currency | Source | Months matching | Largest deviation |")
    w("|---|---|---|---|")
    for currency, (ok, total, worst) in sorted(result.daily_checks.items()):
        source_key = result.daily_sources.get(currency)
        label = _source_label(source_key)
        if source_key == "ecb-exr" and currency != "ZAR":
            label = "derived from the ECB at the parity"
        w(f"| {currency} | {label} | {ok} of {total} | {worst:.2%} |")
    w("")

    w("## Large monthly moves")
    w("")
    w(
        f"Months in which a currency moved more than {ref['large_move']:.0%} against the dollar "
        "(after unit conversion): devaluations and float unifications, to check before they lead "
        "a ranking."
    )
    w("")
    if not result.large_moves:
        w("None.")
    for iso3, month, change in result.large_moves:
        direction = "weakened" if change > 0 else "strengthened"
        w(f"- {names[iso3]}, {month:%B %Y}: {direction} by {abs(change):.0%} against the dollar")
    w("")
    if result.warnings:
        w("## Warnings")
        w("")
        for warning in result.warnings:
            w(f"- {warning}")
        w("")
    return "\n".join(out)
