MATRIX_INDICATORS = (
    "population",
    "land_area",
    "gdp_usd",
    "gdp_ppp",
    "gdp_per_capita_ppp",
    "gdp_growth",
    "inflation",
    "gni_usd",
    "government_debt",
    "military_usd",
    "hdi",
    "external_debt_public",
)
SHORT = {
    "population": "Pop.",
    "land_area": "Land",
    "gdp_usd": "GDP",
    "gdp_ppp": "GDP PPP",
    "gdp_per_capita_ppp": "GDP/cap PPP",
    "gdp_growth": "Growth",
    "inflation": "Infl.",
    "gni_usd": "GNI",
    "government_debt": "Gov. debt",
    "military_usd": "Military",
    "hdi": "HDI",
    "external_debt_public": "Ext. debt",
}


def _specs() -> dict[str, dict[str, Any]]:
    return {s["key"]: s for s in config()["indicators"]}


def complete_years(observations: list[Observation], indicator: str) -> list[int]:
    """Years in which at least the configured share of the 54 states have a figure."""
    threshold = float(config()["complete_year_share"]) * len(countries())
    per_year: dict[int, int] = defaultdict(int)
    for o in observations:
        if o.indicator == indicator:
            per_year[o.year] += 1
    return sorted(y for y, n in per_year.items() if n >= threshold)


def default_window(observations: list[Observation], indicator: str) -> tuple[int, int] | None:
    years = complete_years(observations, indicator)
    if not years:
        return None
    last = years[-1]
    first = min(o.year for o in observations if o.indicator == indicator)
    return max(first, last - 9), last


def latest(observations: list[Observation]) -> dict[tuple[str, str], Observation]:
    result: dict[tuple[str, str], Observation] = {}
    for o in observations:
        key = (o.indicator, o.iso3)
        if key not in result or o.year > result[key].year:
            result[key] = o
    return result


def _money(value: float) -> str:
    for size, suffix in ((1e12, "tn"), (1e9, "bn"), (1e6, "m")):
        if abs(value) >= size:
            return f"{value / size:,.1f} {suffix}"
    return f"{value:,.0f}"


def _regions() -> tuple[dict[str, str], list[str]]:
    """Region names and display order, from the countries seed."""
    seed = json.loads((SEEDS_DIR / "countries.json").read_text(encoding="utf-8"))
    ordered = sorted(seed["regions"], key=lambda r: r["sort_order"])
    return {r["slug"]: r["name"] for r in ordered}, [r["slug"] for r in ordered]


def coverage_matrix(result: Build) -> str:
    latest_of = latest(result.observations)
    out = [
        "# Indicators coverage matrix",
        "",
        "Generated by `python -m pipelines indicators`. Each cell is the latest year with a "
        "figure; `e` marks an IMF estimate (the year before the WEO edition, used where the World "
        "Bank has none); — means no figure in the data kept. Military spending keeps only its "
        "latest ten years (SIPRI fair use). Full definitions: `reference/indicators_config.json`.",
        "",
        "| Country | Region | " + " | ".join(SHORT[k] for k in MATRIX_INDICATORS) + " |",
        "|---|---|" + "---|" * len(MATRIX_INDICATORS),
    ]
    region_names, order = _regions()
    for country in sorted(countries(), key=lambda c: (order.index(c.region), c.name)):
        cells = []
        for key in MATRIX_INDICATORS:
            o = latest_of.get((key, country.iso3))
            cells.append("—" if o is None else f"{o.year}{' e' if o.basis == 'estimate' else ''}")
        out.append(
            f"| {country.name} | {region_names[country.region]} | " + " | ".join(cells) + " |"
        )
    return "\n".join(out) + "\n"


def review_report(result: Build) -> str:
    specs = _specs()
    obs = result.observations
    latest_of = latest(obs)
    names = {c.iso3: c.name for c in countries()}
    out: list[str] = []
    w = out.append

    w("# Indicators review report")
    w("")
    w(
        "Generated by `python -m pipelines indicators` for review before `load`. It is "
        "overwritten each run. Sources and licences: `docs/vinara-sources.md`; rules: "
        "`docs/vinara-method.md`."
    )
    w("")
    w("## Summary")
    w("")
    estimates = [o for o in obs if o.basis == "estimate"]
    w(
        f"- **{len(obs):,} observations** for {len(specs)} indicators and the 54 states, "
        f"{min(o.year for o in obs)}–{max(o.year for o in obs)}; "
        f"**{len(result.creditors):,} creditor rows** of public external debt."
    )
    w("- **Editions read:** " + "; ".join(sorted(result.editions.values())) + ".")
    w(
        f"- **IMF estimates:** {len(estimates)} figures for {result.weo.year - 1} fill gaps in "
        f"the World Bank series ({result.weo.label}); projections ({result.weo.year} on) are "
        "never stored."
    )
    if result.hdr_source == HDR_VIA_OWID.source_key:
        w(
            "- **Human Development Index: read from Our World in Data's copy.** UNDP's own "
            "download (`hdr.undp.org`) did not answer (connections were reset), so the pipeline "
            "used Our World in Data's republication of the same UNDP series (HDR 2025, "
            "1990–2023). The values are UNDP's (CC BY 3.0 IGO); OWID's own terms for "
            "republished data could not be read to confirm. **Decision needed:** accept this "
            "fallback, or provide the UNDP file by hand (saved as `data/raw/indicators/"
            "undp_hdr.csv`, it is used instead)."
        )
    else:
        w("- **Human Development Index:** read from UNDP's own download.")
    w("")

    w("## Coverage by indicator")
    w("")
    w(
        "A year is *complete* when at least 90% of the 54 states have a figure; the default "
        "window is the last ten complete years. *Latest year* counts the states whose most "
        "recent figure is in the last complete year or later."
    )
    w("")
    w(
        "| Indicator | States with data | Latest complete year | Default window | States current "
        "| IMF estimates |"
    )
    w("|---|---|---|---|---|---|")
    for key, spec in specs.items():
        states = {o.iso3 for o in obs if o.indicator == key}
        complete = complete_years(obs, key)
        window = default_window(obs, key)
        last = complete[-1] if complete else None
        current = sum(
            1
            for c in countries()
            if (o := latest_of.get((key, c.iso3))) and last and o.year >= last
        )
        fills = sum(1 for o in estimates if o.indicator == key)
        w(
            f"| {spec['name']} | {len(states)} | {last or '— (no year reaches 90%)'} | "
            f"{f'{window[0]}–{window[1]}' if window else '—'} | {current if last else '—'} | "
            f"{fills or ''} |"
        )
    w("")

    w("## Gaps")
    w("")
    w(
        "States with no figure at all, and states whose latest figure is older than the default "
        "window (they take no part in that metric's ranking, and the site says so). No data is "
        "never shown as zero."
    )
    w("")
    for key, spec in specs.items():
        if key in {"surface_area"} or (
            key.startswith("external_debt_") and key != "external_debt_public"
        ):
            continue
        window = default_window(obs, key)
        missing = [c.name for c in countries() if (key, c.iso3) not in latest_of]
        stale = [
            f"{c.name} ({latest_of[(key, c.iso3)].year})"
            for c in countries()
            if window and (key, c.iso3) in latest_of and latest_of[(key, c.iso3)].year < window[0]
        ]
        if not missing and not stale:
            continue
        line = f"- **{spec['name']}:**"
        if missing:
            line += f" no data for {', '.join(missing)}."
        if stale:
            line += f" Older than the window: {', '.join(stale)}."
        w(line)
    w("")

    w("## IMF estimates used")
    w("")
    if estimates:
        by_indicator: dict[str, list[str]] = defaultdict(list)
        for o in estimates:
            by_indicator[o.indicator].append(names[o.iso3])
        for key, estimated in by_indicator.items():
            if specs[key]["source"] == "weo":
                w(
                    f"- **{specs[key]['name']}** (IMF series): {result.weo.year - 1} is an IMF "
                    f"estimate for all {len(estimated)} states with a figure."
                )
            else:
                listed = ", ".join(sorted(estimated))
                w(f"- **{specs[key]['name']}** ({result.weo.year - 1}): {listed}.")
    else:
        w("None.")
    w("")

    w("## World Bank and IMF compared")
    w("")
    tolerance = config()["cross_check"]
    w(
        "Where both publish a past year, the IMF's figure is compared with the World Bank's (the "
        "one used). Listed: differences above "
        f"{tolerance['relative_tolerance']:.0%} (levels) or {tolerance['points_tolerance']} "
        "percentage points (rates), within the last ten years. Differences are expected where "
        "the two use different base years, PPP rounds or exchange rates; they are reported, not "
        "corrected."
    )
    w("")
    recent = [c for c in result.cross_checks if c.year >= result.weo.year - 11]
    if not recent:
        w("No differences above the tolerance.")
    by_key: dict[str, list[Any]] = defaultdict(list)
    for check in recent:
        by_key[check.indicator].append(check)
    for key, checks in by_key.items():
        spec = specs[key]
        percent = spec["unit"] == "percent"
        checks.sort(
            key=lambda c: (
                -abs(c.wdi - c.imf) if percent else -abs(c.wdi - c.imf) / max(abs(c.wdi), 1)
            )
        )
        affected = sorted({names[c.iso3] for c in checks})
        w(f"### {spec['name']}: {len(checks)} country-years, {len(affected)} states")
        w("")
        w("| State | Year | World Bank | IMF | Difference |")
        w("|---|---|---|---|---|")
        for c in checks[:12]:
            if percent:
                w(
                    f"| {names[c.iso3]} | {c.year} | {c.wdi:.2f} | {c.imf:.2f} | "
                    f"{c.imf - c.wdi:+.2f} pts |"
                )
            else:
                w(
                    f"| {names[c.iso3]} | {c.year} | {_money(c.wdi)} | {_money(c.imf)} | "
                    f"{(c.imf - c.wdi) / c.wdi:+.0%} |"
                )
        if len(checks) > 12:
            w(f"| … {len(checks) - 12} more | | | | |")
        w("")

    w("## Military spending (SIPRI fair use)")
    w("")
    for key, (first, last) in result.trimmed.items():
        values = [o for o in obs if o.indicator == key]
        w(
            f"- **{specs[key]['name']}:** {first}–{last} kept ({len(values)} values for "
            f"{len({o.iso3 for o in values})} states); earlier years are not stored."
        )
    w(
        "- SIPRI's fair use requires non-commercial use and under 10% of its data set; 54 states "
        "over ten years is about 4% per series. Every view and export credits SIPRI."
    )
    w("")

    w("## External debt")
    w("")
    covered = {o.iso3 for o in obs if o.indicator == "external_debt_public"}
    not_covered = sorted(names[c.iso3] for c in countries() if c.iso3 not in covered)
    w(
        f"- **Covered:** {len(covered)} states report to the World Bank's Debtor Reporting "
        f'System. **Not covered:** {", ".join(not_covered) or "none"} (shown as "not covered", '
        "never as zero debt)."
    )
    years = sorted({c.year for c in result.creditors})
    if years:
        w(f"- **Creditors:** {years[0]}–{years[-1]}, {len(result.creditors):,} rows.")
        last_year = years[-1]
        totals: dict[tuple[str, str], float] = defaultdict(float)
        for c in result.creditors:
            if c.year == last_year:
                totals[(c.kind, c.name)] += c.amount_usd
        top = sorted(totals.items(), key=lambda kv: -kv[1])[:10]
        w("")
        w(f"Largest creditors of African public external debt, {last_year} (sum over the states):")
        w("")
        w("| Creditor | Kind | US$ |")
        w("|---|---|---|")
        for (kind, name), amount in top:
            w(f"| {name} | {kind.replace('_', ' ')} | {_money(amount)} |")
    w("")
    debt_notes = [x for x in result.warnings if "sum to" in x]
    if debt_notes:
        w(
            f"**Consistency notes ({len(debt_notes)}):** creditor figures that do not add up to "
            "their totals within 1% and US$1 million."
        )
        w("")
        for note in debt_notes[:20]:
            w(f"- {note}")
        if len(debt_notes) > 20:
            w(f"- … {len(debt_notes) - 20} more.")
    else:
        w("Creditor figures add up to their totals (within 1% and US$1 million).")
    w("")

    w("## Values worth a second look")
    w("")
    w(
        "Not errors: extreme but plausible figures in the last ten years, listed so they are "
        "checked against the source before they lead a ranking."
    )
    w("")
    flagged = [
        o
        for o in obs
        if o.year >= result.weo.year - 11
        and (
            (o.indicator == "inflation" and (o.value > 50 or o.value < -5))
            or (o.indicator == "gdp_growth" and (o.value > 20 or o.value < -15))
            or (o.indicator == "government_debt" and o.value > 150)
        )
    ]
    if not flagged:
        w("None.")
    for o in sorted(flagged, key=lambda o: (o.indicator, o.iso3, o.year)):
        tag = " (IMF estimate)" if o.basis == "estimate" else ""
        source = " (IMF)" if o.source == WEO.source_key and o.basis != "estimate" else ""
        w(f"- {specs[o.indicator]['name']}: {names[o.iso3]} {o.year}: {o.value:,.2f}{tag}{source}")
    w("")
    return "\n".join(out)


def write(result: Build, coverage_path: Path, report_path: Path) -> None:
    coverage_path.write_text(coverage_matrix(result), encoding="utf-8")
    report_path.write_text(review_report(result), encoding="utf-8")
