"""data/mountains_review_report.md: everything a reviewer needs to check the Harim catalogue
before it is built on: the per-country high-point list, every decision and conflict between
sources, what happened to each prototype entry, elevation disagreements, the massif → summit
hierarchy, exclusions, territories, low points, names and sources."""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path
from typing import Any

from .harim_reconcile import Inputs, Mountain, Result

CONFIDENCE = {"high": "high", "medium": "medium", "low": "**low**"}


VOLCANIC_TYPES = {"stratovolcano", "shield_volcano", "volcano"}


def listed_by_gvp(mountain: Mountain) -> bool:
    return any(key.startswith("gvp-") for key, _ in mountain.sources)


def metres(value: float | int | None) -> str:
    if value is None:
        return "—"
    number = round(value)
    sign = "\u2212" if number < 0 else ""  # a true minus sign
    return f"{sign}{abs(number):,} m"


def cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def write(
    path: Path, result: Result, inputs: Inputs, curation: dict[str, Any], dates: dict[str, str]
) -> None:
    names = inputs.country_names
    mountains = result.mountains
    by_key = {m.key: m for m in mountains}
    sources = result.sources.records
    counted = [m for m in mountains if m.summit_kind != "summit" and not m.territory]
    summits = [m for m in mountains if m.summit_kind == "summit"]
    territory = [m for m in mountains if m.territory]
    by_country: dict[str, list[Mountain]] = defaultdict(list)
    for m in counted:
        for iso3 in m.countries:
            by_country[iso3].append(m)
    high_point = {iso3: m for m in counted for iso3 in m.high_point_of}
    review = [m for m in mountains if m.review]

    def why_not_listed(qid: str) -> str:
        if qid in by_key and by_key[qid].parent:
            return f"a summit of {by_key[by_key[qid].parent or ''].name}"
        return "not notable enough to include"

    settings = curation["selection"]

    lines: list[str] = [
        "# Mountains review report (Harim)",
        "",
        "Generated by `python -m pipelines mountains`. Review this before the Harim pages are "
        "built on the data (milestone 8 stop). Edit "
        "`pipelines/africa_pipelines/reference/harim_curation.json` or "
        "`db/seeds/mountain_names.json`, re-run, then `python -m pipelines load`.",
        "",
        "## Summary",
        "",
        f"- **{len(counted)} mountains** in the 54 countries (the counting rule: standalone "
        f"mountains and massifs; a peak shared between countries counts once), plus "
        f"**{len(summits)} summits** of {sum(1 for m in counted if m.summit_kind == 'massif')} "
        f"massifs and **{len(territory)} territory peaks** outside the 54.",
        f"- **{len(review)} records need review** (listed below), "
        f"{sum(1 for p in result.low_points.values() if p.review)} low points too.",
        "- Elevation confidence: "
        + ", ".join(
            f"{level} {sum(1 for m in mountains if m.confidence == level)}"
            for level in ("high", "medium", "low")
        )
        + ".",
        f"- Selection: every country high point, every peak of {settings['always_include_m']:,} m "
        f"or more, every prototype peak, then up to {settings['notable_per_country']} notable "
        f"peaks per country (prominence of {settings['notable_min_prominence_m']} m or more, or "
        f"at least {settings['notable_min_sitelinks']} Wikipedia language editions). Points "
        f"within {settings['subsidiary_km']} km of a higher catalogue mountain (or a massif's own "
        "radius) are treated as parts of it, not separate mountains.",
        "- Elevation: the value most of the most reliable sources agree on (within "
        f"{settings['agree_m']} m); ties go to {', '.join(settings['priority'])}. Confidence "
        f"**high** when those sources agree within {settings['review_m']} m, **medium** within "
        f"{settings['low_m']} m or with one reliable source, **low** beyond that or with one weak "
        f"source. Any disagreement above {settings['review_m']} m (including the prototype) sets "
        "`needs_review`. An outlier against a value that two independent reliable sources agree on "
        "lowers confidence to medium, not low; values that bulk-imported Wikidata items copied "
        'from GeoNames count as GeoNames, not as a second source. (The specification says "more '
        'than 50 m apart → low"; it is applied to the reliable sources, so a wrong prototype '
        "height alone does not make a well-sourced peak low-confidence. Say if you want the "
        "literal reading.)",
        f"- Volcanoes: **{sum(1 for m in counted if m.peak_type in VOLCANIC_TYPES)}** of the "
        "mountains, by Wikidata class (stratovolcano, shield volcano or another volcanic class) "
        "or because the Smithsonian Global Volcanism Program lists them (Wikidata P1886; "
        f"{sum(1 for m in counted if listed_by_gvp(m))} are listed). Status only where Wikidata "
        "states it as a class: "
        + ", ".join(
            f"{status} {sum(1 for m in counted if m.volcanic_status == status)}"
            for status in ("active", "dormant", "extinct")
        )
        + "; the rest are unknown.",
        "",
        "### Sources and as-of dates",
        "",
        f"- Harim prototype: `emtatudatatech/harim@{dates['baseline_commit'][:7]}` "
        f"({dates['baseline_as_of']}), `harim.html` and `README.md`.",
        f"- Wikidata (CC0): query snapshot of {dates['wikidata_as_of']}; each item is cited "
        "individually.",
        f"- The World Factbook, final edition (public domain; the CIA discontinued it in "
        f"February 2026), via factbook.json at `{dates['factbook_commit'][:10]}` "
        f"({dates['factbook_as_of']}): every country's highest and lowest point, as a cross-check.",
        f"- GeoNames (CC BY 4.0): country dumps of {dates['geonames_as_of']}; surveyed "
        "elevations only (the 90 m `dem` column is never used).",
        "- Wikipedia (CC BY-SA): only for curated facts, each with a quote re-checked on every "
        "run.",
        "- Smithsonian Global Volcanism Program: only its volcano numbers, read from Wikidata "
        "(P1886) and linked to each volcano's page; none of its data is copied.",
        "",
        "## Per-country high points (for review)",
        "",
        "| Country | High point | Elevation | Confidence | Shared with | Mountains | Low point "
        "| Relief |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for iso3 in sorted(names, key=lambda i: names[i]):
        m = high_point[iso3]
        low = result.low_points[iso3]
        shared = ", ".join(names[c] for c in sorted(m.countries) if c != iso3)
        flag = " ⚑" if m.review else ""
        relief = (m.elevation_m or 0) - low.elevation_m
        below = ", below sea level" if low.elevation_m < 0 else ""
        low_text = f"{cell(low.name)} ({metres(low.elevation_m)}{below})"
        lines.append(
            f"| {names[iso3]} | {cell(m.name)}{flag} | {metres(m.elevation_m)} | "
            f"{CONFIDENCE[m.confidence or 'low']} | {shared} | {len(by_country[iso3])} | "
            f"{low_text}{' ⚑' if low.review else ''} | {metres(relief)} |"
        )
    lines += ["", "⚑ = needs review (reasons below).", ""]

    lines += ["## Decisions recorded in the curation file", ""]
    lines += [f"- {d}" for d in result.decisions] or ["- None."]
    lines += ["", "## Where the sources disagree on a country's high or low point", ""]
    lines += [f"- {c}" for c in result.conflicts] or ["- None."]

    # Higher Wikidata items that are not in the catalogue (so the high point is not contradicted).
    lines += [
        "",
        "### Wikidata items higher than a country's high point",
        "",
        "Items Wikidata places in a country with a greater elevation than the chosen high point. "
        "None of them is in the catalogue as a separate mountain (they would contradict the high "
        "point); check whether any is a better high point.",
        "",
    ]
    higher_rows = []
    for iso3, peaks in sorted(inputs.candidates.items(), key=lambda kv: names[kv[0]]):
        hp = high_point[iso3]
        for peak in peaks:
            if peak.elevation_m is None or peak.elevation_m <= (hp.elevation_m or 0):
                continue
            if peak.qid in by_key and by_key[peak.qid].summit_kind != "summit":
                continue
            excluded = next(
                (e.reason for e in result.exclusions if e.qid == peak.qid), None
            ) or result.not_peaks.get(peak.qid)
            higher_rows.append(
                f"| {names[iso3]} | {cell(peak.label)} ({peak.qid}) | {metres(peak.elevation_m)} | "
                f"{cell(hp.name)} {metres(hp.elevation_m)} | {peak.sitelinks} | "
                f"{cell(excluded) or why_not_listed(peak.qid)} |"
            )
    if higher_rows:
        lines += [
            "| Country | Item | Elevation | High point | Wikipedia editions | Why not listed |",
            "|---|---|---|---|---|---|",
            *higher_rows,
        ]
    else:
        lines.append("None.")

    lines += [
        "",
        "## The Harim prototype (curated baseline)",
        "",
        "Every entry of `harim.html` (40) and `README.md` (15), what it matched and how its "
        "values compare. The prototype decides which peaks exist; heights come from the sources "
        "above.",
        "",
        "| File | Entry | Prototype | Catalogue | Notes |",
        "|---|---|---|---|---|",
    ]
    for row in result.baseline_report:
        entry = row["entry"]
        matched = by_key.get(row.get("mountain", ""))
        target = matched
        if matched is not None and matched.summit_kind == "massif" and matched.top_summit in by_key:
            target = by_key[matched.top_summit]
        notes = list(row["issues"])
        if (
            target is not None
            and target.elevation_m is not None
            and abs(entry.height_m - target.elevation_m) > 10
        ):
            notes.append(f"height differs by {abs(entry.height_m - target.elevation_m):,} m")
        notes += entry.claims
        where = entry.territory or "/".join(entry.countries)
        catalogue = (
            f"{cell(matched.name)} ({matched.summit_kind}) {metres(matched.elevation_m)}"
            if matched is not None
            else "—"
        )
        lines.append(
            f"| {entry.file} | {cell(entry.raw_name)} | {entry.height_m:,} m, {where} | "
            f"{catalogue} | {cell('; '.join(notes))} |"
        )
    lines += [
        "",
        "Known prototype issues, as checked against the sources:",
        "",
        "- **Emba Soira** is 3,018 m in Wikidata and the Factbook, not 2,586 m.",
        "- **South Africa's** high point is **Mafadi** (3,450 m, on the Lesotho border), not "
        "Cathedral Peak (3,004 m), which stays in the catalogue as a Drakensberg peak.",
        "- **Mount Meru**: README 4,562 m, HTML 4,566 m; Wikidata 4,562 m.",
        "- **Ras Dashen**: Wikidata 4,533 m; the Factbook and the prototype 4,550 m.",
        "- **Mont Nimba** (Mount Richard-Molard, 1,752 m) is the high point of both Guinea and "
        "Côte d'Ivoire. The Nimba Range reaches into Liberia, but its summit does not: Liberia's "
        "high point is Mount Wuteve (1,440 m).",
        "- **Cape Verde** is Cabo Verde; **Piton des Neiges** is in Réunion (a French "
        "department, not one of the 54) and is listed under Territories.",
        "- Names that bundle a range or summit in brackets are split (the bracketed part is kept "
        "as a note, alias or range hint), and README/HTML names for the same peak are merged "
        "(Mount Stanley/Margherita Peak, Kilimanjaro/Kibo).",
        "- The HTML says the array is sorted by height; it is not (see the Notes column). "
        "Nothing relies on source order: the database and API sort.",
        "",
        "## Elevations to review",
        "",
        "| Mountain | Countries | Chosen | Confidence | All values |",
        "|---|---|---|---|---|",
    ]
    for m in sorted(
        (m for m in mountains if any("disagree" in r for r in m.review)),
        key=lambda m: -(m.elevation_m or 0),
    ):
        distinct = sorted(
            {(round(e.metres), e.source) for e in m.elevations}, key=lambda v: (-v[0], v[1])
        )
        values = ", ".join(
            f"{metres(value)} ({sources[source].title if source in sources else source})"
            for value, source in distinct
        )
        where = m.territory or ", ".join(names[c] for c in sorted(m.countries))
        lines.append(
            f"| {cell(m.name)} | {where} | {metres(m.elevation_m)} | "
            f"{CONFIDENCE[m.confidence or 'low']} | {cell(values)} |"
        )

    lines += ["", "## All records that need review", ""]
    for m in sorted(review, key=lambda m: -(m.elevation_m or 0)):
        where = m.territory or ", ".join(names[c] for c in sorted(m.countries))
        lines.append(f"- **{m.name}** ({where}, {metres(m.elevation_m)}): {' '.join(m.review)}")
    for iso3, low in sorted(result.low_points.items(), key=lambda kv: names[kv[0]]):
        if low.review:
            lines.append(
                f"- **{names[iso3]} low point, {low.name}** ({metres(low.elevation_m)}): "
                f"{' '.join(low.review)}"
            )

    lines += [
        "",
        "## Massifs and summits",
        "",
        "Two levels only. A massif counts as one mountain and stands exactly as high as its "
        "highest summit. Every link below is from a cited source.",
        "",
    ]
    for massif in [m for m in mountains if m.summit_kind == "massif"]:
        parts = [s for s in summits if s.parent == massif.key]
        listed = ", ".join(
            f"{s.name} {metres(s.elevation_m)}{' (top)' if s.key == massif.top_summit else ''}"
            for s in sorted(parts, key=lambda s: -(s.elevation_m or 0))
        )
        lines.append(
            f"- **{massif.name}** ({metres(massif.elevation_m)}): {listed}. "
            f"{' '.join(massif.notes)}"
        )
    merges = curation["merges"]
    lines += [
        f"- Merged: {merge['qid']} into {by_key[merge['into']].name} — {merge['reason']}"
        for merge in merges
    ]
    lines += [
        "- Mount Emin, Mount Gessi and Mount Luigi di Savoia are described as Rwenzori massifs, "
        "but no source consulted names their summits, so each is modelled as a single mountain "
        "(no summits are invented). Their heights come from the Rwenzori article.",
    ]

    lines += [
        "",
        "## Excluded from the catalogue",
        "",
        f"Wikidata items of {settings['always_include_m']:,} m or more, or notable ones, that are "
        "not listed as separate mountains, and why.",
        "",
        "| Item | Elevation | Countries | Reason |",
        "|---|---|---|---|",
    ]
    for e in sorted(result.exclusions, key=lambda e: -(e.elevation_m or 0)):
        lines.append(
            f"| {cell(e.name)} ({e.qid}) | {metres(e.elevation_m)} | "
            f"{', '.join(names.get(c, c) for c in e.countries)} | {cell(e.reason)} |"
        )

    lines += ["", "## Territories (not among the 54)", ""]
    lines += [f"- **{m.name}**, {m.territory}: {metres(m.elevation_m)}" for m in territory]
    lines += [
        "",
        "Shown on the map with a neutral marker and in a collapsed group under the summary "
        "table; never counted in country statistics. Western Sahara (disputed) has no "
        "catalogue peaks.",
        "",
        "## Country low points",
        "",
        "| Country | Low point | Elevation | Kind | Notes |",
        "|---|---|---|---|---|",
    ]
    for iso3, low in sorted(result.low_points.items(), key=lambda kv: names[kv[0]]):
        below = " (below sea level)" if low.elevation_m < 0 else ""
        lines.append(
            f"| {names[iso3]} | {cell(low.name)} | {metres(low.elevation_m)}{below} | "
            f"{low.feature_type.replace('_', ' ')} | {cell(' '.join(low.review))} |"
        )

    used_ranges = defaultdict(list)
    for m in counted:
        if m.range_slug:
            used_ranges[m.range_slug].append(m)
    lines += [
        "",
        "## Ranges",
        "",
        "Only curated ranges (with their Wikidata items) are used; a peak joins a range through "
        "Wikidata's 'mountain range' statement when it names one of them, so errors such as "
        "Mount Kenya in 'Mount Kilimanjaro' are ignored. Range descriptions, types and "
        "formation notes arrive with the ranges view (milestone 12), sourced the same way.",
        "",
    ]
    for r in sorted(result.ranges, key=lambda r: r.name):
        members = sorted(used_ranges.get(r.slug, []), key=lambda m: -(m.elevation_m or 0))
        lines.append(
            f"- **{r.name}** ({len(members)}): {', '.join(m.name for m in members[:8])}"
            f"{'\u2026' if len(members) > 8 else ''}"
        )

    lines += ["", "## Local names and name origins", ""]
    for m in sorted(
        (m for m in mountains if m.name_origin or m.local_names),
        key=lambda m: -(m.elevation_m or 0),
    ):
        local = "; ".join(
            f"{n['name']} ({n['language']}{', “' + n['meaning'] + '”' if n.get('meaning') else ''})"
            for n in m.local_names
        )
        flag = " ⚑" if any(r.startswith("Name origin") for r in m.review) else ""
        source = (
            sources[m.name_origin_source].title
            if m.name_origin_source
            else (sources[m.local_names[0]["source"]].title if m.local_names else "")
        )
        lines.append(
            f"- **{m.name}**{flag}: {m.name_origin or ''}"
            f"{(' Local names: ' + local + '.') if local else ''} _({source})_"
        )
    lines += [
        "",
        "Entries need a cited source whose text contains their quote; peaks without such a "
        "source have no name origin (never invented).",
        "",
        "## Validation",
        "",
        "Checked on every run (the run fails otherwise): all 54 countries have exactly one high "
        "point and a low point below it; summits have a massif parent (two levels, no cycles); "
        "each massif equals its highest summit; no high point is a summit; slugs are unique; "
        "elevations are within 0\u20136,000 m; coordinates are inside Africa's box and inside or "
        f"within {settings['border_tolerance_km']} km of every listed country (the 1:50m map "
        "boundaries), with island states warned instead; territory peaks have no country; "
        "every curated quote is found in its source.",
        "",
    ]
    lines += [f"- Warning: {w}" for w in result.warnings] or ["- No warnings."]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
