"""Markdown review report for the state-symbology extraction (data/review_report.md)."""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path
from typing import TYPE_CHECKING, Any
from urllib.parse import urlparse

if TYPE_CHECKING:
    from .extract_pdf import Extraction

SEVERITY_ORDER = {"high": 0, "medium": 1, "low": 2}
STATUS_LABEL = {
    "official": "Official",
    "de_facto": "De facto",
    "inferred": "Inferred",
    "sports_nickname": "Sports nickname",
    "contested": "Contested",
}
RESOLUTION_LABEL = {
    "corrected": "Corrected",
    "status_changed": "Status changed",
    "open": "Open",
}
_STOPWORDS = {
    "with", "from", "land", "the", "and", "of", "for", "that", "this", "area", "people",
}  # fmt: skip


def _cell(text: str | None) -> str:
    return (text or "—").replace("|", "\\|").replace("\n", " ")


def _significant_words(text: str) -> set[str]:
    words = re.findall(r"[A-Za-zÀ-ÿ]{4,}", text.lower())
    return {w for w in words if w not in _STOPWORDS}


def cross_check(profile: dict[str, Any]) -> list[str]:
    """Summary words (table) that never appear in the matching prose (detail)."""
    findings: list[str] = []
    pairs = [
        ("etymology", profile["etymology_summary"], profile["etymology_detail"]),
        ("national symbol", profile["national_symbol_summary"], profile["national_symbol_detail"]),
        ("national animal", profile["national_animal_name"], profile["national_animal_detail"]),
    ]
    for label, summary, detail in pairs:
        if not detail:
            continue
        haystack = detail.lower()
        missing = sorted(w for w in _significant_words(summary) if w[:-1] not in haystack)
        if missing:
            findings.append(f"{label}: table says “{summary}”; not in prose: {', '.join(missing)}")
    return findings


def build_report(extraction: Extraction) -> str:
    countries = extraction.countries
    by_iso3 = {c.iso3: c for c in countries}
    curation = extraction.curation
    region_names = {r["slug"]: r["name"] for r in extraction.regions}
    flagged = [c for c in countries if c.profile["needs_review"]]
    document_sources = [s for s in extraction.sources if s["ref_no"] is not None]
    review_sources = [s for s in extraction.sources if s["ref_no"] is None]
    tiers = Counter(s["reliability_tier"] for s in document_sources)
    citing = Counter(key for c in countries for key in {k for _, k in c.citations})
    resolutions = Counter(i["resolution"] for i in curation["known_issues"])

    out: list[str] = []
    w = out.append
    w("# Review report: state symbology extraction")
    w("")
    w(
        "Generated by `python -m pipelines extract-pdf` from "
        "`data/source/africa-state-symbology.pdf`. Regenerate it after changing the PDF or the "
        "curation files; it is overwritten each run."
    )
    w("")
    w("## Summary")
    w("")
    w(
        f"- **{len(countries)} countries** extracted: "
        + ", ".join(
            f"{region_names[slug]} {n}"
            for slug, n in sorted(
                Counter(c.region for c in countries).items(),
                key=lambda kv: [r["slug"] for r in extraction.regions].index(kv[0]),
            )
        )
        + " (the document's grouping)."
    )
    w(
        f"- **{len(flagged)} of {len(countries)} countries are flagged `needs_review`.** Most "
        "flags come from source reliability: the document cites no primary sources, and "
        f"{tiers['low']} of its {len(document_sources)} works cited are low reliability "
        "(forums, social media, fan wikis, quiz and aggregator sites). Corrections and status "
        "changes do not clear the flag; you clear it once you have checked a record."
    )
    cited_anywhere = {int(v) for v in extraction.document.superscripts}
    never = [r for r in extraction.uncited_refs if r not in cited_anywhere]
    intro_only = [r for r in extraction.uncited_refs if r in cited_anywhere]
    w(
        f"- **Sources:** {tiers['reference']} reference, {tiers['secondary']} secondary, "
        f"{tiers['low']} low, {tiers['primary']} primary. "
        f"{len(never)} works cited are never cited in the text (refs "
        f"{', '.join(map(str, never))}); {len(intro_only)} are cited only in the introduction "
        f"(refs {', '.join(map(str, intro_only))}), not in any country profile."
    )
    w(
        f"- **Citations:** {len(extraction.document.superscripts)} superscript citation numerals "
        "were removed from the text and kept as links to `sources`; validation confirms that no "
        "stray citation digits remain."
    )
    w(
        f"- **Known inconsistencies:** {len(curation['known_issues'])} listed in section 1 "
        f"({sum(1 for i in curation['known_issues'] if i['source'] == 'spec')} from the brief, "
        f"{sum(1 for i in curation['known_issues'] if i['source'] == 'found')} found during "
        f"extraction): {resolutions['corrected']} corrected, {resolutions['status_changed']} "
        f"resolved by an animal-status change, {resolutions['open']} open. "
        f"{len(extraction.corrections)} text corrections are listed with before and after text "
        f"in section 2, each verified against a reference source "
        f"({len(review_sources)} added to `sources`)."
    )
    w(
        "- **Etymology categories** were reviewed and are now set in the data (section 4); "
        f"{sum(1 for c in countries if c.profile['etymology_category'] is None)} countries "
        "have none because no category fits."
    )
    w("")
    w(
        "**How to correct the data:** edit `db/seeds/countries.json` (or `sources.json`), set "
        "`needs_review` to `false` once you have checked a record, then run "
        "`python -m pipelines load`. `extract-pdf` will not overwrite edited seeds unless you "
        "pass `--force`."
    )
    w("")

    # 1. Known issues
    w("## 1. Known inconsistencies")
    w("")
    w(
        "“Brief” = listed in the project brief; “Found” = found during extraction. Severity "
        "reflects how misleading the claim would be if shown as fact."
    )
    w("")
    w("| Severity | Country | Field | Origin | Issue | Resolution |")
    w("|---|---|---|---|---|---|")
    for issue in sorted(
        curation["known_issues"],
        key=lambda i: (SEVERITY_ORDER[i["severity"]], by_iso3[i["iso3"]].name),
    ):
        w(
            f"| {issue['severity']} | {by_iso3[issue['iso3']].name} | "
            f"{issue['field'].replace('_', ' ')} | "
            f"{'Brief' if issue['source'] == 'spec' else 'Found'}"
            f" | {_cell(issue['note'])} | {RESOLUTION_LABEL[issue['resolution']]} |"
        )
    w("")
    for retracted in curation.get("retracted_issues", []):
        w(
            f"**Retracted:** {by_iso3[retracted['iso3']].name}, "
            f"{retracted['field'].replace('_', ' ')}. {retracted['note']}"
        )
        w("")

    # 2. Corrections
    w("## 2. Corrections applied")
    w("")
    w(
        "Each correction was verified on 2026-10-15 against the reference source shown, which is "
        "added to `sources` and cited on the corrected field. They live in "
        "`reference/symbology_curation.json`; a correction whose original text no longer "
        "appears in the extraction fails the run."
    )
    w("")
    for correction in extraction.corrections:
        w(f"### {by_iso3[correction.iso3].name}: {correction.field.replace('_', ' ')}")
        w("")
        w(f"- **Why:** {correction.reason}")
        if correction.source_key:
            source = next(s for s in review_sources if s["source_key"] == correction.source_key)
            w(f"- **Source:** [{source['title']}]({source['url']})")
        w(f"- **Before:** {correction.before or '—'}")
        w(f"- **After:** {correction.after}")
        w("")

    # 3. Animal status
    w("## 3. National animal status")
    w("")
    w(
        "Each record's `animal_status` was assigned by these rules, so the app never presents "
        "an inference as an official fact:"
    )
    w("")
    for rule in curation["animal_status_rules"]:
        name, _, text = rule.partition(":")
        w(f"- **{STATUS_LABEL.get(name.strip(), name)}**:{text}")
    w("")
    status_counts = Counter(c.profile["animal_status"] for c in countries)
    w(
        "Totals: "
        + ", ".join(
            f"{STATUS_LABEL[s]} {status_counts[s]}" for s in STATUS_LABEL if status_counts[s]
        )
        + "."
    )
    w("")
    w("| Country | Animal (table) | Scientific name | Status | Basis |")
    w("|---|---|---|---|---|")
    for c in countries:
        curated = curation["countries"][c.iso3]
        w(
            f"| {c.name} | {_cell(c.profile['national_animal_name'])} | "
            f"{_cell(c.profile['national_animal_scientific'])} | "
            f"{STATUS_LABEL[c.profile['animal_status']]} | "
            f"{_cell(curated['animal_status_reason'])} |"
        )
    w("")

    # 4. Etymology categories
    w("## 4. Etymology categories")
    w("")
    w(
        "The document's introduction defines four categories but assigns them only to a few "
        "examples. These assignments were reviewed (2026-10-15) and are set in "
        "`etymology_category`; “none fits” is stored as empty."
    )
    w("")
    w("| Country | Etymology (table) | Category | Confidence | Reasoning |")
    w("|---|---|---|---|---|")
    for c in countries:
        category, confidence, note = curation["etymology_categories"][c.iso3]
        w(
            f"| {c.name} | {_cell(c.profile['etymology_summary'])} | "
            f"{_cell(category.replace('_', ' ') if category else 'none fits')} | {confidence} | "
            f"{_cell(note)} |"
        )
    w("")

    # 5. Sources
    w("## 5. Sources and reliability tiers")
    w("")
    w(
        "Tiers come from `pipelines/africa_pipelines/reference/source_tiers.json` (by domain). "
        "“Countries” is how many country profiles cite the source. The first table is the "
        "document's works cited; the second lists the reference sources used for corrections."
    )
    w("")
    w("| Ref | Title | Site | Type | Tier | Countries |")
    w("|---|---|---|---|---|---|")
    for s in document_sources:
        host = (urlparse(s["url"]).hostname or "").removeprefix("www.")
        w(
            f"| {s['ref_no']} | [{_cell(s['title'])}]({s['url']}) | {host} | "
            f"{s['source_type'].replace('_', ' ')} | {s['reliability_tier']} | "
            f"{citing.get(s['source_key'], 0)} |"
        )
    w("")
    w("| Source key | Title | Tier | Countries |")
    w("|---|---|---|---|")
    for s in review_sources:
        w(
            f"| `{s['source_key']}` | [{_cell(s['title'])}]({s['url']}) | "
            f"{s['reliability_tier']} | {citing.get(s['source_key'], 0)} |"
        )
    w("")

    # 6. Per-country flags
    w("## 6. Records flagged `needs_review`")
    w("")
    for c in flagged:
        w(f"### {c.name} ({c.iso3})")
        w("")
        for note in c.review_notes:
            w(f"- {note}")
        w("")

    # 7. Cross-check
    w("## 7. Table versus prose cross-check")
    w("")
    w(
        "Automated: significant words in each table summary that do not appear in the matching "
        "prose (after corrections). Most differences are harmless shorthand; the meaningful "
        "ones are also listed in section 1."
    )
    w("")
    any_findings = False
    for c in countries:
        findings = cross_check(c.profile)
        if findings:
            any_findings = True
            w(f"- **{c.name}**: " + "; ".join(findings))
    if not any_findings:
        w("No differences found.")
    w("")

    # 8. Extraction notes
    w("## 8. Extraction notes")
    w("")
    w(
        "- Prose is read span by span: superscript citation numerals are separate spans, so a "
        "year followed by a citation (e.g. “1525” plus ref 4) is never merged into “15254”."
    )
    w(
        "- Table cells that the PDF wrapped mid-word (e.g. “Red/Black/Gre|en”, "
        "“Guinea-Bissa|u”) are re-joined by a geometry rule (a single token that fills the cell "
        "width); the West Africa table's Niger row, split across pages 8–9, is merged."
    )
    w(
        "- Each work cited's URL, rebuilt from the text, must exactly match one of the PDF's link "
        "annotations."
    )
    w(
        "- Country names are normalised to their canonical forms with diacritics (e.g. the "
        "table's “Sao Tome” becomes São Tomé and Príncipe, “Gambia” becomes The Gambia); the "
        "prose and table text are otherwise kept as printed."
    )
    w(
        "- Profile prose is split into fields (etymology, flag, symbol, animal) by a reviewed "
        "sentence mapping in `reference/symbology_curation.json`; a sentence can serve more "
        "than one field (e.g. Uganda's crowned crane)."
    )
    w(
        "- `is_microstate_marker` and the country centroids are set later by the boundaries "
        "pipeline; `regions.color_hex` by the flags pipeline."
    )
    w("")
    return "\n".join(out)


def write_review_report(extraction: Extraction, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_report(extraction), encoding="utf-8")
